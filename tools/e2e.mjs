// End-to-end check with the REAL model, run in CI (GitHub Actions has internet).
//   1. Eval: accuracy + speed of model/prompt configs on Commons photos  -> eval/RESULTS.md
//   2. Demo: drives the real app on a phone-sized screen and records it  -> media/demo.webm + screens
//
// Usage: node tools/e2e.mjs <baseURL> <imagesDir> [eval|demo|all]
import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';

const [base, imagesDir, what = 'all'] = process.argv.slice(2);
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const credits = JSON.parse(fs.readFileSync(path.join(imagesDir, 'credits.json'), 'utf8'));
const dataURL = (f) => 'data:image/jpeg;base64,' + fs.readFileSync(path.join(imagesDir, f)).toString('base64');

// The first config must be the app's default (ai.js DEFAULT_MODEL + all templates): its embeddings are shipped.
const CONFIGS = [
  { id: 'Xenova/clip-vit-base-patch16', templates: 'ensemble' },
  { id: 'Xenova/clip-vit-base-patch16', templates: 'single' },
  { id: 'Xenova/clip-vit-base-patch32', templates: 'ensemble' },
];

async function evaluate(browser) {
  const rows = [];
  const perImage = {};
  for (const cfg of CONFIGS) {
    try {
      await evalConfig(browser, cfg, rows, perImage);
    } catch (e) {
      console.log('config failed', cfg, e.message);
      rows.push({ model: cfg.id, templates: cfg.templates, error: e.message.split('\n')[0] });
    }
  }
  return writeResults(rows, perImage);
}

async function evalConfig(browser, cfg, rows, perImage) {
  const page = await browser.newPage();
  page.on('console', (m) => m.type() === 'error' && console.log('  [page]', m.text().slice(0, 200)));
  await page.goto(`${base}/tools/eval.html`);
  await page.waitForFunction(() => window.harnessReady);
  const t0 = Date.now();
  const info = await page.evaluate(([m, t]) => window.setup(m, t), [cfg.id, cfg.templates]);
  let top1 = 0, top3 = 0, ms = 0;
  const results = [];
  for (const c of credits) {
    const r = await page.evaluate((u) => window.classify(u), dataURL(c.file));
    const names = r.brands.map((b) => b.name);
    const hit1 = names[0] === c.brand, hit3 = names.slice(0, 3).includes(c.brand);
    top1 += hit1; top3 += hit3; ms += r.ms;
    results.push({ file: c.file, truth: c.brand, guess: r.brands[0], top3: names.slice(0, 3), hit1, hit3 });
  }
  const n = credits.length;
  const row = {
    model: cfg.id, templates: cfg.templates, n,
    top1: top1 / n, top3: top3 / n, msPerPhoto: ms / n, setupS: (Date.now() - t0) / 1000, initMs: info.initMs,
    visionMB: info.visionMB,
  };
  console.log(row);
  rows.push(row);
  perImage[`${cfg.id}|${cfg.templates}`] = results;
  if (cfg === CONFIGS[0]) {
    // Ship the default model's text embeddings so phones skip the text-model download.
    const emb = await page.evaluate(() => window.exportEmbeddings());
    const dir = path.join(ROOT, 'data', 'embeddings');
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, cfg.id.replace(/[^\w.-]+/g, '_') + '.json'), JSON.stringify(emb));
    console.log('wrote embeddings for', Object.keys(emb).length, 'labels');
  }
  await page.close();
}

function writeResults(rows, perImage) {
  fs.mkdirSync(path.join(ROOT, 'eval'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'eval', 'results.json'), JSON.stringify({ rows, perImage }, null, 1));
  const pct = (x) => (x * 100).toFixed(0) + '%';
  let md = `# Eval results\n\nGenerated by \`tools/e2e.mjs\` in CI on ${new Date().toISOString().slice(0, 10)}.\n\n`;
  md += `Test set: ${credits.length} freely licensed Wikimedia Commons photos found by searching each brand name ` +
    `(${new Set(credits.map((c) => c.brand)).size} brands). Not all show litter, and some are noisy matches. Treat this as a smoke test, not a benchmark. ` +
    `Chance level for top-1 is about ${pct(1 / 42)}.\n\n`;
  md += '| Model | Prompts | Top-1 | Top-3 | ms / photo (CI CPU) | Phone download |\n|---|---|---|---|---|---|\n';
  for (const r of rows) {
    md += r.error
      ? `| \`${r.model}\` | ${r.templates} | failed: ${r.error} | | | |\n`
      : `| \`${r.model}\` | ${r.templates} | ${pct(r.top1)} | ${pct(r.top3)} | ${r.msPerPhoto.toFixed(0)} | ${r.visionMB.toFixed(0)} MB |\n`;
  }
  md += '\n## Per photo (default config)\n\n| Photo | Truth | AI top guess | In top 3? |\n|---|---|---|---|\n';
  for (const r of perImage[`${CONFIGS[0].id}|${CONFIGS[0].templates}`] || []) {
    md += `| ${r.file} | ${r.truth} | ${r.guess.name} (${pct(r.guess.score)}) | ${r.hit3 ? '✅' : '❌'} |\n`;
  }
  fs.writeFileSync(path.join(ROOT, 'eval', 'RESULTS.md'), md);
  return perImage[`${CONFIGS[0].id}|${CONFIGS[0].templates}`];
}

async function caption(page, text) {
  await page.evaluate((t) => {
    let el = document.getElementById('__cap');
    if (!el) {
      el = document.createElement('div');
      el.id = '__cap';
      el.style.cssText = 'position:fixed;left:10px;right:10px;bottom:70px;z-index:9999;background:rgba(10,30,18,.92);' +
        'color:#fff;font:600 17px/1.35 system-ui,sans-serif;padding:12px 14px;border-radius:12px;text-align:center;' +
        'box-shadow:0 4px 18px rgba(0,0,0,.35);transition:opacity .25s';
      document.body.append(el);
    }
    el.textContent = t;
    el.style.opacity = t ? '1' : '0';
  }, text);
}

const pause = (ms) => new Promise((r) => setTimeout(r, ms));

async function pickBrand(page, brand) {
  const on = await page.locator('#brand-chips .chip.on').allTextContents();
  if (on.some((t) => t.startsWith(brand))) return;
  const chip = page.locator('#brand-chips .chip', { hasText: brand });
  if (await chip.count()) await chip.first().click();
  else await page.fill('#brand-other', brand);
}

async function snap(page, file, shotName) {
  await page.setInputFiles('#photo', path.join(imagesDir, file));
  await page.waitForSelector('#answer:not([hidden])', { timeout: 60000 });
  await page.evaluate(() => document.getElementById('result').scrollIntoView({ block: 'start' }));
  if (shotName) await page.screenshot({ path: path.join(ROOT, 'media', 'screens', shotName) });
}

async function demo(perImage) {
  // Pick photos honestly: two the AI got right and one it got wrong, so the video shows the correction step.
  const right = [], seen = new Set();
  for (const r of [...perImage].filter((r) => r.hit1).sort((a, b) => b.guess.score - a.guess.score)) {
    if (!seen.has(r.truth)) { right.push(r); seen.add(r.truth); }
    if (right.length === 3) break;
  }
  const wrong = perImage.find((r) => !r.hit1 && r.hit3) || perImage.find((r) => !r.hit1);
  if (right.length < 2) throw new Error('not enough correctly recognised photos for a demo');

  const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'kk-'));
  const viewport = { width: 390, height: 844 };
  const videoSize = { width: viewport.width * 2, height: viewport.height * 2 }; // record at device-pixel resolution
  // Warm-up run (not recorded): the one-time model download.
  let ctx = await chromium.launchPersistentContext(profile, { viewport });
  let page = ctx.pages()[0] || await ctx.newPage();
  await page.goto(base + '/');
  await page.waitForSelector('#model-card[hidden]', { state: 'attached', timeout: 300000 });
  await ctx.close();

  fs.mkdirSync(path.join(ROOT, 'media', 'screens'), { recursive: true });
  const vidDir = fs.mkdtempSync(path.join(os.tmpdir(), 'kkv-'));
  ctx = await chromium.launchPersistentContext(profile, {
    viewport, deviceScaleFactor: 2, recordVideo: { dir: vidDir, size: videoSize },
    permissions: ['clipboard-read', 'clipboard-write'],
  });
  page = ctx.pages()[0] || await ctx.newPage();
  await page.goto(base + '/');
  await caption(page, 'Kiska Kachra: whose trash is this? 🗑️');
  await page.waitForSelector('#model-card[hidden]', { state: 'attached', timeout: 120000 });
  await pause(1500);
  await caption(page, 'Go for a walk. Pick up litter. Snap it.');
  await pause(2200);
  await page.screenshot({ path: path.join(ROOT, 'media', 'screens', '1-home.png') });

  await caption(page, 'The open-weight CLIP model runs on the phone. No server, no upload.');
  await snap(page, right[0].file, '2-guess.png');
  await pause(2600);
  await caption(page, `Recognised: ${right[0].truth}. Tap "Log it".`);
  await pickBrand(page, right[0].truth);
  await pause(1600);
  await page.click('#log-btn');
  await pause(1200);

  await snap(page, right[1].file);
  await caption(page, `Another one: ${right[1].truth}.`);
  await pickBrand(page, right[1].truth);
  await pause(2200);
  await page.click('#log-btn');
  await pause(1000);

  if (wrong) {
    await snap(page, wrong.file, '3-correct.png');
    await caption(page, `Wrong guess (${wrong.guess.name})? One tap fixes it. A human confirms every entry.`);
    await pause(2600);
    await pickBrand(page, wrong.truth);
    await pause(1400);
    await page.click('#log-btn');
    await pause(1000);
  }

  await snap(page, right[2]?.file || right[0].file);
  await caption(page, 'Not on the list? Type the brand. The AI learns it on the device.');
  await pause(1200);
  await page.fill('#brand-other', 'Kwality Walls');
  await pause(1400);
  await page.click('#log-btn');
  await pause(2200);

  await caption(page, 'Airplane mode ✈️ It still works offline.');
  await ctx.setOffline(true);
  await page.reload();
  await caption(page, 'Airplane mode ✈️ It still works offline.');
  await page.waitForSelector('#model-card[hidden]', { state: 'attached', timeout: 60000 });
  await snap(page, right[0].file);
  await pickBrand(page, right[0].truth);
  await pause(2000);
  await page.click('#log-btn');
  await pause(800);

  await caption(page, "At the end of the walk you get a brand audit: who's littering your street.");
  await page.evaluate(() => document.getElementById('total').closest('.card').scrollIntoView({ block: 'start' }));
  await pause(800);
  await page.screenshot({ path: path.join(ROOT, 'media', 'screens', '4-audit.png') });
  await pause(2200);
  await page.click('#share-btn');
  await caption(page, 'Share it, or export a CSV for your clean-up group.');
  await pause(2600);
  await caption(page, 'Open source (MIT): github.com/Ankan0503/hf26-week1. Now go touch grass 🌳');
  await pause(3200);
  const video = page.video();
  await ctx.close();
  fs.copyFileSync(await video.path(), path.join(ROOT, 'media', 'demo.webm'));

  const used = [right[0], right[1], right[2], wrong].filter(Boolean).map((r) => r.file);
  const cred = credits.filter((c) => used.includes(c.file));
  fs.writeFileSync(path.join(ROOT, 'media', 'CREDITS.md'),
    '# Photo credits for the demo video\n\nTest photos from Wikimedia Commons, used under their licenses:\n\n' +
    cred.map((c) => `- [${c.title}](${c.url}) by ${c.author || 'unknown'}, ${c.license}`).join('\n') + '\n');
}

const browser = await chromium.launch();
let perImage;
if (what !== 'demo') perImage = await evaluate(browser);
if (!perImage) throw new Error('default config produced no results; see eval/RESULTS.md');
else perImage = JSON.parse(fs.readFileSync(path.join(ROOT, 'eval', 'results.json'), 'utf8')).perImage[`${CONFIGS[0].id}|${CONFIGS[0].templates}`];
await browser.close();
if (what !== 'eval') await demo(perImage);
console.log('done');
